const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
module.exports = async function(win, logs, data) {
  const run = code => win.webContents.executeJavaScript(code);
  const choose = page => run(`[...document.querySelectorAll('.md-nav button')].find(el => el.textContent === ${JSON.stringify(page)}).click()`);
  const shot = async name => { await sleep(500); fs.writeFileSync(path.join(logs, name + '.png'), (await win.webContents.capturePage()).toPNG()); };
  const bridge = (kind, payload = {}, id = crypto.randomUUID()) => run(`new Promise((resolve,reject)=>{const frame=document.querySelector('.md-yc-frame');const id=${JSON.stringify(id)};const timer=setTimeout(()=>{window.removeEventListener('message',receive);reject(new Error('bridge timeout'))},30000);function receive(event){if(event.origin!=='http://127.0.0.1:13001'||event.source!==frame.contentWindow||event.data?.type!=='media-workbench:agent-result'||event.data.requestId!==id)return;clearTimeout(timer);window.removeEventListener('message',receive);if(event.data.ok)resolve(event.data.result);else reject(new Error(event.data.error))}window.addEventListener('message',receive);frame.contentWindow.postMessage({type:'media-workbench:agent',requestId:id,kind:${JSON.stringify(kind)},...${JSON.stringify(payload)}},'http://127.0.0.1:13001')})`);
  const getContext = async expected => {
    for (let i = 0; i < 100; i++) { try { const context = await bridge('context'); if (!expected || context.id === expected) return context; } catch {} await sleep(300); }
    throw new Error('context not ready');
  };
  const pages = ['灵感','内容','排期','影策','复盘','风格'];
  for (const page of pages) {
    await choose(page); await sleep(150);
    const layout = await run(`(()=>{const bar=document.querySelector('.md-topbar'),main=document.querySelector('.md-main');return {height:bar.getBoundingClientRect().height,bg:getComputedStyle(bar).backgroundColor,width:bar.scrollWidth,available:main.clientWidth}})()`);
    assert.equal(layout.height,56,JSON.stringify({page,layout})); assert.equal(layout.bg,'rgba(0, 0, 0, 0)'); assert.ok(layout.width <= layout.available + 2,JSON.stringify({page,layout}));
  }
  await choose('灵感'); await shot('unified-inspiration');
  await choose('内容'); await shot('unified-content');
  await choose('排期'); await shot('unified-schedule');
  await choose('影策'); await getContext();
  assert.ok(await run(`Boolean(document.querySelector('.md-dock'))`));
  await run(`document.querySelector('.md-topbar button[aria-label="收起全局助手"]').click()`);
  assert.equal(await run(`localStorage.getItem('media-workbench:dock')`),'closed');
  await choose('内容'); await choose('影策'); assert.equal(await run(`Boolean(document.querySelector('.md-dock'))`),false);
  await run(`document.querySelector('.md-topbar button[aria-label="打开全局助手"]').click()`);
  await shot('unified-yingce');
  win.setSize(1100,800); await shot('unified-narrow'); win.setSize(1440,960);
  const initial = await getContext();
  const projectResult = await bridge('execute', { context: initial, action: { op: 'create_project', name: `自动验收项目-${crypto.randomUUID().slice(0,8)}`, description: '项目初稿' } });
  const projectId = projectResult.text.split('：')[1];
  await bridge('execute', { context: initial, action: { op: 'open_project', id: projectId } });
  let projectContext = await getContext(projectId);
  await bridge('execute', { context: projectContext, action: { op: 'update_project', id: projectId, description: '项目更新稿' } });
  projectContext = await getContext(projectId);
  assert.equal(projectContext.description, '项目更新稿');
  await bridge('execute', { context: projectContext, action: { op: 'create_unit', id: projectId, title: '第一集', text: '分集初稿' } });
  projectContext = await getContext(projectId);
  await bridge('execute', { context: projectContext, action: { op: 'update_unit', id: projectId, unitId: projectContext.units[0].id, text: '分集修改稿' } });
  projectContext = await getContext(projectId);
  const draft = await bridge('execute', { context: projectContext, action: { op: 'read_unit', id: projectId, unitId: projectContext.units[0].id } });
  assert.equal(JSON.parse(draft.text).text, '分集修改稿');
  const createId=crypto.randomUUID();
  const create = await bridge('execute',{context:projectContext,action:{op:'create_canvas',title:'自动验收画布（隔离数据）'}},createId);
  assert.deepEqual(await bridge('execute',{context:initial,action:{op:'create_canvas',title:'重复请求'}},createId),create);
  const id = create.text.split('：')[1];
  let context=await getContext(id);
  const stale=context;
  await bridge('execute',{context,action:{op:'add_node',title:'验收文字',text:'第一版'}});
  await assert.rejects(bridge('execute',{context:stale,action:{op:'add_node',text:'不应写入'}}));
  context=await getContext(id); assert.equal(context.nodes.length,1); assert.equal(context.nodes[0].prompt,'第一版');
  await bridge('execute',{context,action:{op:'update_node',nodeId:context.nodes[0].id,text:'第二版'}});
  context=await getContext(id); assert.equal(context.nodes[0].prompt,'第二版');
  await bridge('execute',{context,action:{op:'undo_canvas'}});
  context=await getContext(id); assert.equal(context.nodes[0].prompt,'第一版');
  await bridge('execute',{context,action:{op:'add_node',title:'第二个节点',text:'连接测试'}});
  context=await getContext(id);
  await bridge('execute',{context,action:{op:'connect_nodes',fromId:context.nodes[0].id,toId:context.nodes[1].id}});
  const frame=win.webContents.mainFrame.frames.find(frame=>frame.url.includes('/canvas/'));
  await frame.executeJavaScript('location.reload()');
  context=await getContext(id); assert.equal(context.nodes.length,2);
  await choose('影策');
  await frame.executeJavaScript(`location.href='/assets'`); await sleep(1500);
  const library=await win.webContents.session.fetch('http://127.0.0.1:13001/api/workbench/local-assets'); assert.equal(library.status,200);
  assert.equal((await fetch('http://127.0.0.1:13001/api/workbench/local-assets')).status,401);
  const file=path.join(data,'local-index-test.txt');fs.writeFileSync(file,'local preview');
  require('./local-assets.cjs').importPaths(path.join(data,'local-assets.json'),[file]);
  const indexed=await (await win.webContents.session.fetch('http://127.0.0.1:13001/api/workbench/local-assets')).json();
  const preview=await win.webContents.session.fetch('http://127.0.0.1:13001'+indexed.rows[0].url);assert.equal(await preview.text(),'local preview');
  await frame.executeJavaScript('location.reload()');await sleep(1500);await shot('unified-local-assets');
  fs.writeFileSync(path.join(logs,'unified-smoke.json'),JSON.stringify({ok:true,pages,projectDrafts:true,duplicateSafe:true,conflictSafe:true,canvasSaved:true,undo:true,reload:true,localAssets:true},null,2));
};
